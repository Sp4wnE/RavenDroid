"""Stable context-local GLES procedure slots; no driver state is inferred."""
import argparse,json,re
from pathlib import Path
ROOT=Path(__file__).resolve().parents[1]
def generate(check=False):
    names={x['name'][1:] for x in json.loads((ROOT/'native-runtime/abi-inventory.json').read_text())['imports'] if x.get('name','').startswith('_gl')}
    for p in (ROOT/'native-runtime/src/graphics').rglob('*.rs'):
        if p.name!='slots.rs':names.update(re.findall(r'"(gl[A-Z][A-Za-z0-9_]+)"',p.read_text(encoding='utf-8')))
    names=sorted(names)
    body='// Generated by tools/generate_gl_slots.py. Context-local addresses only.\n'
    body+=f'pub(super) const COUNT:usize={len(names)};\npub(super) fn slot(name:&str)->Option<usize>{{Some(match name{{\n'
    body+=''.join(f'    "{name}"=>{i},\n' for i,name in enumerate(names))
    body+='    _=>return None,\n})}\n'
    p=ROOT/'native-runtime/src/graphics/slots.rs'
    if check:
        if p.read_text(encoding='utf-8')!=body:raise ValueError('Stale GLES slots')
    else:p.write_text(body,encoding='utf-8')
if __name__=='__main__':
    parser=argparse.ArgumentParser();parser.add_argument('--check',action='store_true');generate(parser.parse_args().check)
